package main

import (
	"bytes"
	"go/format"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

type genOptions struct {
	// Release enables update checks against the release catalog.
	Release bool
}

var mainTmpl = template.Must(template.New("main").Parse(`// Code generated by dwb. DO NOT EDIT.

package main

import (
	"embed"

	dw "github.com/cdro/desktopwidgets-core/runtime"
{{- if .HasGo}}

	_ "{{.Import}}"
{{- end}}
)

//go:embed widget.yml icon.png frontend
var files embed.FS

func main() {
	dw.Main(files, dw.Build{
		AppID:       {{printf "%q" .AppID}},
		ReleaseRepo: {{printf "%q" .ReleaseRepo}},
		CatalogURL:  {{printf "%q" .CatalogURL}},
	})
}
`))

// generate writes gen/<id>/: a main package that embeds a copy of the
// widget's manifest, icon and frontend and links its optional Go code.
func generate(r *repo, u *unit, opts genOptions) (string, error) {
	dir := filepath.Join(r.Root, "gen", u.M.ID)
	if err := os.RemoveAll(dir); err != nil {
		return "", err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	src := filepath.Join(r.Root, filepath.FromSlash(u.Dir))
	for _, f := range []string{"widget.yml", "icon.png"} {
		if err := copyFile(filepath.Join(src, f), filepath.Join(dir, f)); err != nil {
			return "", err
		}
	}
	if err := copyTree(filepath.Join(src, "frontend"), filepath.Join(dir, "frontend")); err != nil {
		return "", err
	}

	data := map[string]any{
		"HasGo":       u.HasGo,
		"Import":      u.ImportPath(),
		"AppID":       r.Project.AppID(u.M),
		"ReleaseRepo": r.Project.ReleaseRepo,
		"CatalogURL":  "",
	}
	if opts.Release {
		data["CatalogURL"] = r.Project.CatalogURL()
	}
	var buf bytes.Buffer
	if err := mainTmpl.Execute(&buf, data); err != nil {
		return "", err
	}
	src2, err := format.Source(buf.Bytes())
	if err != nil {
		return "", err
	}
	return dir, os.WriteFile(filepath.Join(dir, "main.go"), src2, 0o644)
}

func copyFile(src, dst string) error {
	data, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	return os.WriteFile(dst, data, 0o644)
}

func copyTree(src, dst string) error {
	return filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(src, p)
		if strings.HasPrefix(d.Name(), ".") && rel != "." {
			if d.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		out := filepath.Join(dst, rel)
		if d.IsDir() {
			return os.MkdirAll(out, 0o755)
		}
		return copyFile(p, out)
	})
}
